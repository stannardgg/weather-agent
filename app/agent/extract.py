# 「XX市 / XX县 / XX省」里的 XX 若含这些字，基本可以确定不是地名
# （例：「问题在市里怎么解决」会抽出「问题」）。白名单优先，这一层只兜住带后缀的误伤。
_NON_PLACE_CHARS = set("的了不有是要和在吗呢吧么多少情况时候问题怎么如何为对把被让使能做说来去")
_RE_CITY_SUFFIX = re.compile(r"([\u4e00-\u9fa5]{2,4})(?:市|县)")


def today_cst() -> date:
    """东八区的「今天」。抽日期用它作基准，不用 UTC。"""
    return datetime.now(_CST).date()


def extract_date(question: str, *, today: date | None = None) -> str | None:
    """从问题里抽出目标日期，返回 `YYYY-MM-DD`；抽不到返回 None（= 不限日期）。

    识别优先级（先具体后模糊）：
    1. 完整日期 `2026-10-20` / `2026年10月20日`
    2. 月日 `10月20日`（按当年解析）
    3. 相对词 `今天 / 明天 / 后天 / 大后天`
    4. 星期 `周三 / 下周三 / 星期三`
    """
    text = (question or "").strip()
    if not text:
        return None
    base = today or today_cst()

    match = _RE_ISO_DATE.search(text)
    if match:
        year, month, day = (int(part) for part in match.groups())
        try:
            return date(year, month, day).isoformat()
        except ValueError:
            # 非法日期（如 2026-02-30）当作没抽到，而不是抛错——用户可能只是顺手打了个数字
            return None

    match = _RE_MONTH_DAY.search(text)
    if match:
        month, day = (int(part) for part in match.groups())
        try:
            return date(base.year, month, day).isoformat()
        except ValueError:
            return None

    for keyword in _RELATIVE_DAY_KEYWORDS:
        if keyword in text:
            return (base + timedelta(days=_RELATIVE_DAYS[keyword])).isoformat()

    match = _RE_WEEKDAY.search(text)
    if match:
        next_week = match.group(1) is not None
        index = _WEEKDAY_INDEX[match.group(2)]
        # 本周内的目标日：今天是周三问「周三」→ 就是今天（差 0 天），问「周五」→ 差 2 天；
        # 问「周一」→ 已过去，取下周的周一（差 5 天）。这是口语里最自然的理解。
        delta = (index - base.weekday()) % 7
        if next_week:
            delta += 7
        return (base + timedelta(days=delta)).isoformat()

    return None


def extract_city(question: str, *, extra: Iterable[str] = ()) -> str | None:
    """从问题里猜城市名；猜不到返回 None。

    `extra` 用于传「用户自己知识库里出现过的地名」之类的外部候选（本阶段未接，
    预留参数是为了将来不用改函数签名）。

    顺序：白名单（长词优先）→ 带「市/县」后缀的写法。
    白名单优先是为了降低「南京路」这类误伤——先命中的是准确度更高的那条路。
    """
    text = (question or "").strip()
    if not text:
        return None

    candidates = sorted({*_COMMON_CITIES, *extra}, key=len, reverse=True)
    for city in candidates:
        if city in text:
            return city

    for match in _RE_CITY_SUFFIX.finditer(text):
        name = match.group(1)
        # 含「的/是/问/时」这类字的，几乎一定不是地名（见 _NON_PLACE_CHARS 的说明）
        if set(name) & _NON_PLACE_CHARS:
            continue
        return name
    return None
